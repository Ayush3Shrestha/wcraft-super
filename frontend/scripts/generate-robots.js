// Writes public/robots.txt before each build/start. The sitemap is served by
// the backend, so its address comes from REACT_APP_API_URL.
// Run automatically by the prebuild / prestart npm scripts.
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
// Same .env files react-scripts reads, without adding a dependency
for (const file of [".env", ".env.local", `.env.${process.env.NODE_ENV || "production"}`, `.env.${process.env.NODE_ENV || "production"}.local`]) {
  const full = path.join(root, file);
  if (!fs.existsSync(full)) continue;
  for (const line of fs.readFileSync(full, "utf8").split(/\r?\n/)) {
    const match = /^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/.exec(line);
    if (match && process.env[match[1]] === undefined) process.env[match[1]] = match[2].replace(/^["']|["']$/g, "");
  }
}

const apiUrl = (process.env.REACT_APP_API_URL || "http://localhost:8081/api").replace(/\/+$/, "");
const sitemap = `${apiUrl.replace(/\/api$/, "")}/sitemap.xml`;

const robots = `# Generated by scripts/generate-robots.js; edit that file instead.
User-agent: *
Allow: /
Disallow: /admin
Disallow: /cart
Disallow: /checkout

Sitemap: ${sitemap}
`;

fs.writeFileSync(path.join(root, "public", "robots.txt"), robots);
console.log(`robots.txt written (sitemap: ${sitemap})`);
